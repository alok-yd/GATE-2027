/**
 * Seeds all historical report data into localStorage if not already initialized,
 * or forces an update to ensure 100% fidelity with the progress report.
 */
export const seedHistoricalData = (force: boolean = false): void => {
  if (typeof window === 'undefined' || !window.localStorage) return;

  const SEED_VERSION_KEY = 'gate_report_seeded_2026_09_16_v3';
  const alreadySeeded = localStorage.getItem(SEED_VERSION_KEY);

  if (alreadySeeded && !force) {
    return;
  }

  // 1. Streak Data
  localStorage.setItem('gate_streak_data', JSON.stringify(HISTORICAL_STREAK));

  // 2. Syllabus Subjects (525/525 completed)
  localStorage.setItem('gate_subjects', JSON.stringify(HISTORICAL_SUBJECTS));
  HISTORICAL_SUBJECTS.forEach((sub) => {
    localStorage.setItem(`lectures_${sub.id}`, String(sub.totalLectures));
  });

  // 3. Weekly Targets
  HISTORICAL_WEEKLY_TARGETS.forEach((target) => {
    localStorage.setItem(`gate_weekly_target_${target.weekId}`, JSON.stringify(target));
  });

  // 4. Daily Logs
  HISTORICAL_DAILY_LOGS.forEach((log) => {
    localStorage.setItem(`gate_daily_target_${log.date}`, JSON.stringify(log));
  });

  // 5. PYQ Practice Entries (1,153 Total PYQs Solved across 41 entries)
  localStorage.setItem('gate_pyq_entries', JSON.stringify(HISTORICAL_PYQ_ENTRIES));

  // 6. Test Performance & Mock Results (20 Recorded Tests)
  localStorage.setItem('gate_mocks', JSON.stringify(HISTORICAL_MOCKS));

  // Mark as seeded
  localStorage.setItem(SEED_VERSION_KEY, 'true');

  // Trigger storage update
  window.dispatchEvent(new Event('storage'));
};
